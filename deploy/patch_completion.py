"""Apply one reviewable stdout compatibility patch to the pinned local runtime.

llama-completion sends its EOG banner through the same output channel as tokens.
Keep generated bytes intact; move only that fixed banner to debug logging.
"""
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RELATIVE = 'tools/completion/completion.cpp'
BEFORE = b'            LOG(" [end of text]\\n");'
AFTER = b'            LOG_DBG(" [end of text]\\n");'


def main():
    source = ROOT/'local/llama.cpp'
    lock = json.loads((ROOT/'deploy/pi-lock.json').read_text())
    command = ['git', '-c', f'safe.directory={source}', '-C', str(source)]
    if subprocess.check_output(command+['rev-parse', 'HEAD'], text=True).strip() != lock['llama_cpp_commit']:
        raise ValueError('llama.cpp commit differs from the lock')
    changed = subprocess.check_output(command+['diff', 'HEAD', '--name-only'], text=True).splitlines()
    if set(changed) - {RELATIVE}:
        raise ValueError('Unexpected modified llama.cpp sources; preserve them before provisioning')
    original = subprocess.check_output(command+['show', f'HEAD:{RELATIVE}'])
    if original.count(BEFORE) != 1:
        raise ValueError('Pinned completion source does not match the expected patch context')
    patched = original.replace(BEFORE, AFTER)
    target = source/RELATIVE
    current = target.read_bytes()
    if current not in (original, patched):
        raise ValueError('Completion source has unrelated local changes')
    if current != patched:
        target.write_bytes(patched)
    print('Applied quiet-eog-v1: only the fixed EOG banner becomes debug output')


if __name__ == '__main__':
    main()
